#!/usr/bin/env node
/* Copy docs/ask/fixtures into assets/js/ask-fixtures.js for the browser mock.
   The fixture directory itself is not modified. */
"use strict";

var fs = require("fs");
var path = require("path");

var root = path.resolve(__dirname, "../..");
var fixtureDir = path.join(root, "docs/ask/fixtures");
var manifest = JSON.parse(fs.readFileSync(path.join(fixtureDir, "manifest.json"), "utf8"));
var files = {};

manifest.cases.forEach(function (item) {
  var name = item.response;
  if (files[name]) return;
  files[name] = {
    status: item.status,
    contentType: item.contentType,
    body: fs.readFileSync(path.join(fixtureDir, name), "utf8")
  };
});

var payload = {
  contractVersion: manifest.contractVersion,
  files: files
};

var output = [
  "/* Generated by tools/ask/embed-fixtures.js from docs/ask/fixtures. Do not edit by hand. */",
  "(function (root) {",
  "  root.ASK_FIXTURES = " + JSON.stringify(payload) + ";",
  "})(typeof globalThis !== \"undefined\" ? globalThis : this);",
  ""
].join("\n");

var target = path.join(root, "assets/js/ask-fixtures.js");
fs.writeFileSync(target, output);
process.stdout.write("wrote " + path.relative(root, target) + "\n");
